-- Optional ACCOUNTADMIN step. A Resource Monitor controls warehouse credits;
-- this Snowflake budget adds separate visibility/alerting for Agent spend.
USE ROLE ACCOUNTADMIN;
GRANT CREATE TAG ON SCHEMA RETAILPULSE_AI.GOVERNANCE TO ROLE RETAILPULSE_DEMO_ROLE;
GRANT CREATE SNOWFLAKE.CORE.BUDGET ON SCHEMA RETAILPULSE_AI.GOVERNANCE TO ROLE RETAILPULSE_DEMO_ROLE;

USE ROLE RETAILPULSE_DEMO_ROLE;
USE DATABASE RETAILPULSE_AI;
USE SCHEMA GOVERNANCE;

CREATE TAG IF NOT EXISTS COST_CENTER
  ALLOWED_VALUES 'RETAILPULSE_DEMO';

ALTER AGENT RETAILPULSE_AI.AGENT.RETAILPULSE_AGENT
  SET TAG RETAILPULSE_AI.GOVERNANCE.COST_CENTER = 'RETAILPULSE_DEMO';

CREATE OR REPLACE SNOWFLAKE.CORE.BUDGET RETAILPULSE_AGENT_BUDGET();
CALL RETAILPULSE_AGENT_BUDGET!SET_SPENDING_LIMIT(5);

CALL RETAILPULSE_AGENT_BUDGET!SET_RESOURCE_TAGS(
  [[
    (SELECT SYSTEM$REFERENCE(
      'TAG',
      'RETAILPULSE_AI.GOVERNANCE.COST_CENTER',
      'SESSION',
      'applybudget'
    )),
    'RETAILPULSE_DEMO'
  ]],
  'UNION'
);

CALL RETAILPULSE_AGENT_BUDGET!GET_CONFIG();
