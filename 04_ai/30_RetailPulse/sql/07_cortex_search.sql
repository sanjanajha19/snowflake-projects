USE ROLE RETAILPULSE_DEMO_ROLE;
USE DATABASE RETAILPULSE_AI;
USE SCHEMA SEARCH;

CREATE OR REPLACE CORTEX SEARCH SERVICE PRODUCT_EXPERIENCE_SEARCH
  ON CONTENT
  PRIMARY KEY (DOCUMENT_ID)
  ATTRIBUTES DOCUMENT_TYPE, PRODUCT_ID, CATEGORY, REGION, ISSUE_TYPE, EVENT_DATE
  WAREHOUSE = RETAILPULSE_DEMO_WH
  TARGET_LAG = '1 day'
  EMBEDDING_MODEL = 'snowflake-arctic-embed-m-v1.5'
AS
SELECT
  DOCUMENT_ID,
  CONTENT,
  TITLE,
  DOCUMENT_TYPE,
  PRODUCT_ID,
  CATEGORY,
  REGION,
  ISSUE_TYPE,
  EVENT_DATE
FROM RETAILPULSE_AI.DATA.DOCUMENTS;

GRANT USAGE ON CORTEX SEARCH SERVICE PRODUCT_EXPERIENCE_SEARCH
  TO ROLE RETAILPULSE_DEMO_ROLE;

-- Smoke test: returns the most relevant product/customer evidence as JSON.
SELECT PARSE_JSON(
  SNOWFLAKE.CORTEX.SEARCH_PREVIEW(
    'RETAILPULSE_AI.SEARCH.PRODUCT_EXPERIENCE_SEARCH',
    '{
      "query": "coffee machine leaking reservoir returns and customer complaints",
      "columns": ["DOCUMENT_ID", "TITLE", "CONTENT", "PRODUCT_ID", "ISSUE_TYPE"],
      "filter": {"@eq": {"PRODUCT_ID": "PRD-0042"}},
      "limit": 5
    }'
  )
) AS SEARCH_RESULTS;
