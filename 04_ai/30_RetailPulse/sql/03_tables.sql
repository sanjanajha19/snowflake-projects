USE ROLE RETAILPULSE_DEMO_ROLE;
USE WAREHOUSE RETAILPULSE_DEMO_WH;
USE DATABASE RETAILPULSE_AI;
USE SCHEMA DATA;

CREATE OR REPLACE TABLE STORES (
  STORE_ID VARCHAR PRIMARY KEY, STORE_NAME VARCHAR, FORMAT VARCHAR, REGION VARCHAR,
  CITY VARCHAR, LATITUDE NUMBER(9,6), LONGITUDE NUMBER(9,6), FLOOR_SPACE_SQFT NUMBER
);

CREATE OR REPLACE TABLE PRODUCTS (
  PRODUCT_ID VARCHAR PRIMARY KEY, PRODUCT_NAME VARCHAR, CATEGORY VARCHAR, SUBCATEGORY VARCHAR,
  BRAND VARCHAR, UNIT_COST_USD NUMBER(10,2), LIST_PRICE_USD NUMBER(10,2),
  SHELF_LIFE_DAYS NUMBER, LEAD_TIME_DAYS NUMBER, ACTIVE BOOLEAN
);

CREATE OR REPLACE TABLE INVENTORY (
  STORE_ID VARCHAR, PRODUCT_ID VARCHAR, SNAPSHOT_DATE DATE, ON_HAND_QTY NUMBER,
  RESERVED_QTY NUMBER, IN_TRANSIT_QTY NUMBER, SAFETY_STOCK_QTY NUMBER,
  REORDER_POINT_QTY NUMBER, LAST_REPLENISHMENT_DATE DATE,
  PRIMARY KEY (STORE_ID,PRODUCT_ID,SNAPSHOT_DATE)
);

CREATE OR REPLACE TABLE SALES (
  SALE_ID VARCHAR PRIMARY KEY, SALE_TIME TIMESTAMP_NTZ, STORE_ID VARCHAR, PRODUCT_ID VARCHAR,
  CHANNEL VARCHAR, UNITS NUMBER, GROSS_SALES_USD NUMBER(12,2), DISCOUNT_USD NUMBER(12,2),
  NET_SALES_USD NUMBER(12,2), COST_USD NUMBER(12,2), PROMOTION_ID VARCHAR
);

CREATE OR REPLACE TABLE PROMOTIONS (
  PROMOTION_ID VARCHAR PRIMARY KEY, PROMOTION_NAME VARCHAR, CATEGORY VARCHAR,
  START_DATE DATE, END_DATE DATE, DISCOUNT_PCT NUMBER(5,2), CHANNEL VARCHAR, REGION VARCHAR
);

CREATE OR REPLACE TABLE RETURNS (
  RETURN_ID VARCHAR PRIMARY KEY, SALE_ID VARCHAR, STORE_ID VARCHAR, PRODUCT_ID VARCHAR,
  RETURN_DATE DATE, UNITS NUMBER, REFUND_USD NUMBER(12,2), REASON_CODE VARCHAR
);

CREATE OR REPLACE TABLE DOCUMENTS (
  DOCUMENT_ID VARCHAR PRIMARY KEY, DOCUMENT_TYPE VARCHAR, TITLE VARCHAR, PRODUCT_ID VARCHAR,
  CATEGORY VARCHAR, REGION VARCHAR, ISSUE_TYPE VARCHAR, EVENT_DATE DATE,
  RATING NUMBER(2,1), CONTENT VARCHAR, RELATIVE_PATH VARCHAR
);

CREATE OR REPLACE TABLE RETAIL_ACTION_QUEUE (
  ACTION_ID VARCHAR DEFAULT UUID_STRING(), ACTION_TYPE VARCHAR, PRODUCT_ID VARCHAR,
  FROM_STORE_ID VARCHAR, TO_STORE_ID VARCHAR, QUANTITY NUMBER, REASON VARCHAR,
  ESTIMATED_REVENUE_PROTECTED_USD NUMBER(12,2), STATUS VARCHAR DEFAULT 'PENDING_APPROVAL',
  REQUESTED_BY VARCHAR DEFAULT CURRENT_USER(), REQUESTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  APPROVED_BY VARCHAR, APPROVED_AT TIMESTAMP_LTZ, EXTERNAL_REFERENCE VARCHAR,
  PRIMARY KEY (ACTION_ID)
);

