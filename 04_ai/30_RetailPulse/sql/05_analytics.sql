CREATE OR REPLACE VIEW V_INVENTORY_CONTROL_TOWER AS
WITH velocity AS (
  SELECT STORE_ID, PRODUCT_ID,
         SUM(IFF(SALE_TIME>=DATEADD('day',-7,CURRENT_TIMESTAMP()),UNITS,0))/7.0 AVG_DAILY_UNITS_7D,
         SUM(IFF(SALE_TIME>=DATEADD('day',-28,CURRENT_TIMESTAMP()),UNITS,0))/28.0 AVG_DAILY_UNITS_28D,
         SUM(IFF(SALE_TIME>=DATEADD('day',-7,CURRENT_TIMESTAMP()),NET_SALES_USD,0)) NET_SALES_7D_USD
  FROM DATA.SALES GROUP BY 1,2
), active_promo AS (
  SELECT CATEGORY, MAX(PROMOTION_ID) PROMOTION_ID, MAX(PROMOTION_NAME) PROMOTION_NAME,
         MAX(DISCOUNT_PCT) DISCOUNT_PCT
  FROM DATA.PROMOTIONS
  WHERE CURRENT_DATE() BETWEEN START_DATE AND END_DATE
  GROUP BY 1
)
SELECT i.STORE_ID, st.STORE_NAME, st.REGION, st.CITY,
       i.PRODUCT_ID, p.PRODUCT_NAME, p.CATEGORY, p.SUBCATEGORY, p.BRAND,
       p.LIST_PRICE_USD, p.UNIT_COST_USD, p.LEAD_TIME_DAYS,
       i.ON_HAND_QTY, i.RESERVED_QTY, i.IN_TRANSIT_QTY, i.SAFETY_STOCK_QTY, i.REORDER_POINT_QTY,
       GREATEST(i.ON_HAND_QTY-i.RESERVED_QTY,0) AVAILABLE_QTY,
       COALESCE(v.AVG_DAILY_UNITS_7D,0) AVG_DAILY_UNITS_7D,
       COALESCE(v.AVG_DAILY_UNITS_28D,0) AVG_DAILY_UNITS_28D,
       COALESCE(v.NET_SALES_7D_USD,0) NET_SALES_7D_USD,
       ROUND(GREATEST(i.ON_HAND_QTY-i.RESERVED_QTY,0)/NULLIF(v.AVG_DAILY_UNITS_7D,0),2) DAYS_OF_SUPPLY,
       ap.PROMOTION_ID, ap.PROMOTION_NAME, ap.DISCOUNT_PCT,
       IFF(ap.PROMOTION_ID IS NOT NULL,TRUE,FALSE) ACTIVE_PROMOTION,
       IFF(COALESCE(GREATEST(i.ON_HAND_QTY-i.RESERVED_QTY,0)/NULLIF(v.AVG_DAILY_UNITS_7D,0),999)<=7,TRUE,FALSE) STOCKOUT_RISK_7D,
       GREATEST(0,CEIL(7*COALESCE(v.AVG_DAILY_UNITS_7D,0)-GREATEST(i.ON_HAND_QTY-i.RESERVED_QTY+i.IN_TRANSIT_QTY,0))) REQUIRED_QTY_7D,
       GREATEST(0,FLOOR(GREATEST(i.ON_HAND_QTY-i.RESERVED_QTY,0)-i.SAFETY_STOCK_QTY-14*COALESCE(v.AVG_DAILY_UNITS_7D,0))) TRANSFERABLE_EXCESS_QTY,
       ROUND(GREATEST(0,7*COALESCE(v.AVG_DAILY_UNITS_7D,0)-GREATEST(i.ON_HAND_QTY-i.RESERVED_QTY+i.IN_TRANSIT_QTY,0))*p.LIST_PRICE_USD,2) REVENUE_AT_RISK_USD
FROM DATA.INVENTORY i
JOIN DATA.STORES st ON st.STORE_ID=i.STORE_ID
JOIN DATA.PRODUCTS p ON p.PRODUCT_ID=i.PRODUCT_ID
LEFT JOIN velocity v ON v.STORE_ID=i.STORE_ID AND v.PRODUCT_ID=i.PRODUCT_ID
LEFT JOIN active_promo ap ON ap.CATEGORY=p.CATEGORY
WHERE i.SNAPSHOT_DATE=(SELECT MAX(SNAPSHOT_DATE) FROM DATA.INVENTORY);

CREATE OR REPLACE VIEW V_TRANSFER_RECOMMENDATIONS AS
SELECT risk.PRODUCT_ID, risk.PRODUCT_NAME, risk.CATEGORY,
       excess.STORE_ID FROM_STORE_ID, excess.STORE_NAME FROM_STORE_NAME,
       risk.STORE_ID TO_STORE_ID, risk.STORE_NAME TO_STORE_NAME,
       LEAST(excess.TRANSFERABLE_EXCESS_QTY,risk.REQUIRED_QTY_7D) RECOMMENDED_QTY,
       risk.REVENUE_AT_RISK_USD,
       ROUND(LEAST(excess.TRANSFERABLE_EXCESS_QTY,risk.REQUIRED_QTY_7D)*risk.LIST_PRICE_USD,2) ESTIMATED_REVENUE_PROTECTED_USD
FROM V_INVENTORY_CONTROL_TOWER risk
JOIN V_INVENTORY_CONTROL_TOWER excess
  ON excess.PRODUCT_ID=risk.PRODUCT_ID AND excess.STORE_ID<>risk.STORE_ID
WHERE risk.STOCKOUT_RISK_7D=TRUE
  AND risk.REQUIRED_QTY_7D>0
  AND excess.TRANSFERABLE_EXCESS_QTY>0;

CREATE OR REPLACE VIEW V_RETAIL_SALES AS
SELECT s.SALE_ID, s.SALE_TIME, s.STORE_ID, st.STORE_NAME, st.REGION, st.CITY,
       s.PRODUCT_ID, p.PRODUCT_NAME, p.CATEGORY, p.SUBCATEGORY, p.BRAND,
       s.CHANNEL, s.UNITS, s.GROSS_SALES_USD, s.DISCOUNT_USD, s.NET_SALES_USD,
       s.COST_USD, s.NET_SALES_USD-s.COST_USD GROSS_MARGIN_USD,
       ROUND(100*(s.NET_SALES_USD-s.COST_USD)/NULLIF(s.NET_SALES_USD,0),2) GROSS_MARGIN_PCT,
       s.PROMOTION_ID, pr.PROMOTION_NAME, pr.DISCOUNT_PCT
FROM DATA.SALES s
JOIN DATA.STORES st ON st.STORE_ID=s.STORE_ID
JOIN DATA.PRODUCTS p ON p.PRODUCT_ID=s.PRODUCT_ID
LEFT JOIN DATA.PROMOTIONS pr ON pr.PROMOTION_ID=s.PROMOTION_ID;

CREATE OR REPLACE VIEW V_PRODUCT_EXPERIENCE AS
WITH sale AS (
  SELECT PRODUCT_ID, SUM(UNITS) SOLD_UNITS, SUM(NET_SALES_USD) NET_SALES_USD
  FROM DATA.SALES GROUP BY 1
), ret AS (
  SELECT PRODUCT_ID, SUM(UNITS) RETURNED_UNITS, SUM(REFUND_USD) REFUND_USD,
         COUNT_IF(REASON_CODE='DEFECT') DEFECT_RETURN_COUNT
  FROM DATA.RETURNS GROUP BY 1
), doc AS (
  SELECT PRODUCT_ID, COUNT_IF(DOCUMENT_TYPE='PRODUCT_REVIEW') REVIEW_COUNT,
         AVG(IFF(DOCUMENT_TYPE='PRODUCT_REVIEW',RATING,NULL)) AVG_REVIEW_RATING,
         COUNT_IF(DOCUMENT_TYPE='SUPPORT_CASE') SUPPORT_CASE_COUNT,
         COUNT_IF(ISSUE_TYPE='QUALITY') QUALITY_SIGNAL_COUNT
  FROM DATA.DOCUMENTS WHERE PRODUCT_ID IS NOT NULL GROUP BY 1
)
SELECT p.PRODUCT_ID, p.PRODUCT_NAME, p.CATEGORY, p.SUBCATEGORY, p.BRAND,
       COALESCE(s.SOLD_UNITS,0) SOLD_UNITS, COALESCE(s.NET_SALES_USD,0) NET_SALES_USD,
       COALESCE(r.RETURNED_UNITS,0) RETURNED_UNITS, COALESCE(r.REFUND_USD,0) REFUND_USD,
       COALESCE(r.DEFECT_RETURN_COUNT,0) DEFECT_RETURN_COUNT,
       ROUND(100*COALESCE(r.RETURNED_UNITS,0)/NULLIF(s.SOLD_UNITS,0),2) RETURN_RATE_PCT,
       COALESCE(d.REVIEW_COUNT,0) REVIEW_COUNT, d.AVG_REVIEW_RATING,
       COALESCE(d.SUPPORT_CASE_COUNT,0) SUPPORT_CASE_COUNT,
       COALESCE(d.QUALITY_SIGNAL_COUNT,0) QUALITY_SIGNAL_COUNT
FROM DATA.PRODUCTS p
LEFT JOIN sale s ON s.PRODUCT_ID=p.PRODUCT_ID
LEFT JOIN ret r ON r.PRODUCT_ID=p.PRODUCT_ID
LEFT JOIN doc d ON d.PRODUCT_ID=p.PRODUCT_ID;

