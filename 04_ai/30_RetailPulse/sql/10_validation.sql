USE ROLE RETAILPULSE_DEMO_ROLE;
USE DATABASE RETAILPULSE_AI;
USE WAREHOUSE RETAILPULSE_DEMO_WH;

-- 1. Confirm the synthetic dataset is populated.
SELECT 'STORES' AS OBJECT_NAME, COUNT(*) AS ROW_COUNT FROM DATA.STORES
UNION ALL SELECT 'PRODUCTS', COUNT(*) FROM DATA.PRODUCTS
UNION ALL SELECT 'INVENTORY', COUNT(*) FROM DATA.INVENTORY
UNION ALL SELECT 'SALES', COUNT(*) FROM DATA.SALES
UNION ALL SELECT 'PROMOTIONS', COUNT(*) FROM DATA.PROMOTIONS
UNION ALL SELECT 'RETURNS', COUNT(*) FROM DATA.RETURNS
UNION ALL SELECT 'DOCUMENTS', COUNT(*) FROM DATA.DOCUMENTS
ORDER BY OBJECT_NAME;

-- 2. The flagship demo story: low supply and revenue risk at selected stores.
SELECT
  STORE_ID, STORE_NAME, PRODUCT_ID, PRODUCT_NAME, AVAILABLE_QTY,
  SALES_VELOCITY_7D, DAYS_OF_SUPPLY, REQUIRED_QTY_7D,
  STOCKOUT_RISK_7D, ESTIMATED_REVENUE_RISK_7D
FROM ANALYTICS.V_INVENTORY_CONTROL_TOWER
WHERE PRODUCT_ID = 'PRD-0042'
ORDER BY STOCKOUT_RISK_7D DESC, ESTIMATED_REVENUE_RISK_7D DESC;

-- 3. A safe, data-backed transfer candidate should be returned.
SELECT *
FROM ANALYTICS.V_TRANSFER_RECOMMENDATIONS
WHERE PRODUCT_ID = 'PRD-0042'
ORDER BY ESTIMATED_REVENUE_PROTECTED DESC;

-- 4. Structured return and product-experience signals.
SELECT *
FROM ANALYTICS.V_PRODUCT_EXPERIENCE
WHERE PRODUCT_ID = 'PRD-0042';

-- 5. SQL fallback for customer evidence, independent of Cortex Search.
SELECT DOCUMENT_ID, TITLE, DOCUMENT_TYPE, ISSUE_TYPE, CONTENT
FROM ANALYTICS.V_DOCUMENT_SEARCH_FALLBACK
WHERE PRODUCT_ID = 'PRD-0042'
ORDER BY EVENT_DATE DESC;

-- 6. Guardrail test: unsafe requests are rejected and do not enter the queue.
CALL AGENT.CREATE_TRANSFER_REQUEST(
  'PRD-0042', 'STR-011', 'STR-011', 10, 'Negative validation test'
);

-- 7. Confirm deployed governed objects.
SHOW SEMANTIC VIEWS IN SCHEMA ANALYTICS;
SHOW CORTEX SEARCH SERVICES IN SCHEMA SEARCH;
SHOW AGENTS IN SCHEMA AGENT;
SHOW RESOURCE MONITORS LIKE 'RETAILPULSE_DEMO_MONITOR';

-- 8. Inspect action requests created during the live demo.
SELECT *
FROM DATA.RETAIL_ACTION_QUEUE
ORDER BY REQUESTED_AT DESC;

-- 9. Inspect cost telemetry (latency may apply to account-usage views).
