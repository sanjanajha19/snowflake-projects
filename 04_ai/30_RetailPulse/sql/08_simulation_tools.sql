USE ROLE RETAILPULSE_DEMO_ROLE;
USE DATABASE RETAILPULSE_AI;
USE SCHEMA AGENT;
USE WAREHOUSE RETAILPULSE_DEMO_WH;

CREATE OR REPLACE PROCEDURE SIMULATE_POS_EVENTS(EVENT_COUNT NUMBER)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_count NUMBER DEFAULT LEAST(GREATEST(COALESCE(EVENT_COUNT, 25), 1), 200);
  v_batch VARCHAR DEFAULT 'SIM-' || TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYYMMDDHH24MISSFF3');
BEGIN
  INSERT INTO RETAILPULSE_AI.DATA.SALES (
    SALE_ID, SOLD_AT, STORE_ID, PRODUCT_ID, QUANTITY, UNIT_PRICE,
    DISCOUNT_AMOUNT, NET_SALES, COST_AMOUNT, CHANNEL, PROMOTION_ID
  )
  SELECT
    :v_batch || '-' || LPAD(SEQ4()::VARCHAR, 4, '0'),
    DATEADD('second', -SEQ4() * 7, CURRENT_TIMESTAMP()),
    'STR-' || LPAD((1 + MOD(SEQ4(), 20))::VARCHAR, 3, '0'),
    'PRD-' || LPAD((1 + MOD(SEQ4() * 7, 60))::VARCHAR, 4, '0'),
    1 + MOD(SEQ4(), 3),
    p.LIST_PRICE,
    IFF(MOD(SEQ4(), 4) = 0, ROUND(p.LIST_PRICE * 0.10, 2), 0),
    ROUND((1 + MOD(SEQ4(), 3)) * p.LIST_PRICE
      - IFF(MOD(SEQ4(), 4) = 0, p.LIST_PRICE * 0.10, 0), 2),
    ROUND((1 + MOD(SEQ4(), 3)) * p.UNIT_COST, 2),
    IFF(MOD(SEQ4(), 3) = 0, 'ONLINE', 'STORE'),
    IFF(MOD(SEQ4(), 4) = 0, 'PROMO-WEEKEND-HOME', NULL)
  FROM TABLE(GENERATOR(ROWCOUNT => 200)) g
  JOIN RETAILPULSE_AI.DATA.PRODUCTS p
    ON p.PRODUCT_ID = 'PRD-' || LPAD((1 + MOD(SEQ4() * 7, 60))::VARCHAR, 4, '0')
  QUALIFY ROW_NUMBER() OVER (ORDER BY SEQ4()) <= :v_count;

  MERGE INTO RETAILPULSE_AI.DATA.INVENTORY target
  USING (
    SELECT STORE_ID, PRODUCT_ID, SUM(QUANTITY) AS SOLD_QTY
    FROM RETAILPULSE_AI.DATA.SALES
    WHERE SALE_ID LIKE :v_batch || '-%'
    GROUP BY STORE_ID, PRODUCT_ID
  ) source
    ON target.STORE_ID = source.STORE_ID AND target.PRODUCT_ID = source.PRODUCT_ID
  WHEN MATCHED THEN UPDATE SET
    target.ON_HAND_QTY = GREATEST(target.ON_HAND_QTY - source.SOLD_QTY, 0),
    target.UPDATED_AT = CURRENT_TIMESTAMP();

  RETURN OBJECT_CONSTRUCT(
    'status', 'SUCCESS',
    'batch_id', :v_batch,
    'events_inserted', :v_count,
    'message', 'Synthetic POS events loaded and inventory reduced.'
  );
END;
$$;

CREATE OR REPLACE PROCEDURE CREATE_TRANSFER_REQUEST(
  PRODUCT_ID VARCHAR,
  FROM_STORE_ID VARCHAR,
  TO_STORE_ID VARCHAR,
  QUANTITY NUMBER,
  REASON VARCHAR
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_action_id VARCHAR DEFAULT UUID_STRING();
  v_source_excess NUMBER;
  v_destination_need NUMBER;
  v_unit_price NUMBER(12,2);
  v_approved_qty NUMBER;
BEGIN
  IF (PRODUCT_ID IS NULL OR FROM_STORE_ID IS NULL OR TO_STORE_ID IS NULL
      OR QUANTITY IS NULL OR QUANTITY <= 0) THEN
    RETURN OBJECT_CONSTRUCT('status', 'REJECTED', 'reason', 'Product, both stores, and a positive quantity are required.');
  END IF;

  IF (FROM_STORE_ID = TO_STORE_ID) THEN
    RETURN OBJECT_CONSTRUCT('status', 'REJECTED', 'reason', 'Source and destination stores must differ.');
  END IF;

  SELECT COALESCE(MAX(TRANSFERABLE_EXCESS_QTY), 0)
    INTO :v_source_excess
  FROM RETAILPULSE_AI.ANALYTICS.V_INVENTORY_CONTROL_TOWER
  WHERE PRODUCT_ID = :PRODUCT_ID AND STORE_ID = :FROM_STORE_ID;

  SELECT COALESCE(MAX(REQUIRED_QTY_7D), 0)
    INTO :v_destination_need
  FROM RETAILPULSE_AI.ANALYTICS.V_INVENTORY_CONTROL_TOWER
  WHERE PRODUCT_ID = :PRODUCT_ID AND STORE_ID = :TO_STORE_ID;

  SELECT MAX(LIST_PRICE) INTO :v_unit_price
  FROM RETAILPULSE_AI.DATA.PRODUCTS
  WHERE PRODUCT_ID = :PRODUCT_ID;

  v_approved_qty := LEAST(QUANTITY, v_source_excess, v_destination_need);

  IF (v_unit_price IS NULL) THEN
    RETURN OBJECT_CONSTRUCT('status', 'REJECTED', 'reason', 'Unknown product.');
  END IF;

  IF (v_approved_qty <= 0) THEN
    RETURN OBJECT_CONSTRUCT(
      'status', 'REJECTED',
      'reason', 'No safe transfer quantity: source has no excess or destination has no seven-day need.'
    );
  END IF;

  INSERT INTO RETAILPULSE_AI.DATA.RETAIL_ACTION_QUEUE (
    ACTION_ID, ACTION_TYPE, PRODUCT_ID, FROM_STORE_ID, TO_STORE_ID,
    REQUESTED_QUANTITY, RECOMMENDED_QUANTITY, ESTIMATED_REVENUE_PROTECTED,
    REASON, STATUS, REQUESTED_BY, REQUESTED_AT
  ) VALUES (
    :v_action_id, 'INVENTORY_TRANSFER', :PRODUCT_ID, :FROM_STORE_ID, :TO_STORE_ID,
    :QUANTITY, :v_approved_qty, ROUND(:v_approved_qty * :v_unit_price, 2),
    :REASON, 'PENDING_APPROVAL', CURRENT_USER(), CURRENT_TIMESTAMP()
  );

  RETURN OBJECT_CONSTRUCT(
    'status', 'PENDING_APPROVAL',
    'action_id', :v_action_id,
    'recommended_quantity', :v_approved_qty,
    'estimated_revenue_protected', ROUND(:v_approved_qty * :v_unit_price, 2),
    'message', 'Request recorded only; no inventory was moved.'
  );
END;
$$;

GRANT USAGE ON PROCEDURE SIMULATE_POS_EVENTS(NUMBER) TO ROLE RETAILPULSE_DEMO_ROLE;
GRANT USAGE ON PROCEDURE CREATE_TRANSFER_REQUEST(VARCHAR, VARCHAR, VARCHAR, NUMBER, VARCHAR)
  TO ROLE RETAILPULSE_DEMO_ROLE;
