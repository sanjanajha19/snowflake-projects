-- Change the quota for your own trial. This controls warehouse credits only.
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE RESOURCE MONITOR RETAILPULSE_DEMO_MONITOR
  WITH CREDIT_QUOTA=20
       FREQUENCY=NEVER
       START_TIMESTAMP=IMMEDIATELY
       TRIGGERS
         ON 50 PERCENT DO NOTIFY
         ON 75 PERCENT DO NOTIFY
         ON 90 PERCENT DO SUSPEND
         ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE RETAILPULSE_DEMO_WH
  SET RESOURCE_MONITOR=RETAILPULSE_DEMO_MONITOR
      AUTO_SUSPEND=60
      AUTO_RESUME=TRUE
      STATEMENT_TIMEOUT_IN_SECONDS=300;

GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE RETAILPULSE_DEMO_ROLE;

USE ROLE RETAILPULSE_DEMO_ROLE;
USE DATABASE RETAILPULSE_AI;
USE SCHEMA GOVERNANCE;

CREATE OR REPLACE PROCEDURE SUSPEND_DEMO_COMPUTE()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER
AS
$$
BEGIN
  ALTER WAREHOUSE RETAILPULSE_DEMO_WH SUSPEND;
  RETURN 'RETAILPULSE_DEMO_WH suspended. Control serverless AI separately.';
END;
$$;

CREATE OR REPLACE VIEW V_WAREHOUSE_USAGE AS
SELECT START_TIME, END_TIME, WAREHOUSE_NAME, CREDITS_USED,
       CREDITS_USED_COMPUTE, CREDITS_USED_CLOUD_SERVICES
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME='RETAILPULSE_DEMO_WH'
  AND START_TIME>=DATEADD('day',-30,CURRENT_TIMESTAMP());

CREATE OR REPLACE VIEW V_CORTEX_SEARCH_USAGE AS
SELECT START_TIME, END_TIME, DATABASE_NAME, SCHEMA_NAME, SERVICE_NAME, CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_SEARCH_SERVING_USAGE_HISTORY
WHERE DATABASE_NAME='RETAILPULSE_AI'
  AND START_TIME>=DATEADD('day',-30,CURRENT_TIMESTAMP());

CREATE OR REPLACE VIEW V_CORTEX_AGENT_USAGE AS
SELECT START_TIME, END_TIME, USER_NAME, AGENT_NAME, TOKEN_CREDITS, TOKENS, METADATA
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE AGENT_DATABASE_NAME='RETAILPULSE_AI'
  AND START_TIME>=DATEADD('day',-30,CURRENT_TIMESTAMP());

