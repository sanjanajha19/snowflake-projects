USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RETAILPULSE_DEMO_ROLE
  COMMENT = 'Owner and runtime role for the RetailPulse AI demonstration';

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE RETAILPULSE_DEMO_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE RETAILPULSE_DEMO_ROLE;

CREATE WAREHOUSE IF NOT EXISTS RETAILPULSE_DEMO_WH
  WAREHOUSE_SIZE='X-SMALL'
  AUTO_SUSPEND=60
  AUTO_RESUME=TRUE
  INITIALLY_SUSPENDED=TRUE
  STATEMENT_TIMEOUT_IN_SECONDS=300
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS=60
  COMMENT='Cost-controlled warehouse for RetailPulse AI';

CREATE DATABASE IF NOT EXISTS RETAILPULSE_AI
  COMMENT='Synthetic retail inventory, merchandising, and customer-experience demo';

CREATE SCHEMA IF NOT EXISTS RETAILPULSE_AI.DATA;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE_AI.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE_AI.SEARCH;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE_AI.AGENT;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE_AI.GOVERNANCE;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE_AI.APP;

GRANT USAGE, OPERATE ON WAREHOUSE RETAILPULSE_DEMO_WH TO ROLE RETAILPULSE_DEMO_ROLE;
GRANT OWNERSHIP ON DATABASE RETAILPULSE_AI TO ROLE RETAILPULSE_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE RETAILPULSE_AI TO ROLE RETAILPULSE_DEMO_ROLE COPY CURRENT GRANTS;
GRANT ROLE RETAILPULSE_DEMO_ROLE TO USER IDENTIFIER(CURRENT_USER());

USE ROLE RETAILPULSE_DEMO_ROLE;
USE WAREHOUSE RETAILPULSE_DEMO_WH;
USE DATABASE RETAILPULSE_AI;

